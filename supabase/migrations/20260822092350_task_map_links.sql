create or replace function public.nl_protect_task_owned_map_place()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
    if new.folder_id is distinct from old.folder_id
       and exists (
           select 1
           from public.task_map_links as link
           where link.place_id = old.id
             and link.relationship = 'owner'
       ) then
        raise exception 'Save this task-owned place permanently before moving it';
    end if;

    if new.kind = 'parked'
       and new.kind is distinct from old.kind
       and exists (
           select 1
           from public.task_map_links as link
           where link.place_id = old.id
       ) then
        raise exception 'A task-linked place cannot become a parked place';
    end if;

    return new;
end;
$$;

