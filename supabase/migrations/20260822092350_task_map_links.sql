create table public.task_map_links (
    id bigint generated by default as identity primary key,
    task_id bigint not null
        references public.tasks (id)
        on delete cascade,
    place_id bigint
        references public.map_places (id)
        on delete cascade,
    route_id bigint
        references public.map_routes (id)
        on delete cascade,
    relationship text not null default 'reference'
        check (relationship in ('owner', 'reference')),
    position integer not null default 0
        check (position >= 0),
    client_draft_id uuid,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint task_map_links_one_target_check check (
        (place_id is not null and route_id is null)
        or (place_id is null and route_id is not null)
    ),
    constraint task_map_links_route_reference_only_check check (
        route_id is null or relationship = 'reference'
    ),
    constraint task_map_links_client_draft_owner_only_check check (
        client_draft_id is null
        or (relationship = 'owner' and place_id is not null)
    )
);

comment on table public.task_map_links is
    'Live task relationships for saved map places and routes. Owner links are exclusive, task-created places.';

create index task_map_links_task_position_idx
    on public.task_map_links (task_id, position, id);

create index task_map_links_place_idx
    on public.task_map_links (place_id, task_id)
    where place_id is not null;

create index task_map_links_route_idx
    on public.task_map_links (route_id, task_id)
    where route_id is not null;

create unique index task_map_links_task_place_unique_idx
    on public.task_map_links (task_id, place_id)
    where place_id is not null;

create unique index task_map_links_task_route_unique_idx
    on public.task_map_links (task_id, route_id)
    where route_id is not null;

create unique index task_map_links_one_place_owner_idx
    on public.task_map_links (place_id)
    where relationship = 'owner' and place_id is not null;

create unique index task_map_links_client_draft_unique_idx
    on public.task_map_links (client_draft_id)
    where client_draft_id is not null;

