create or replace function public.nl_delete_task(
    p_task_id bigint,
    p_preserved_places jsonb default '[]'::jsonb
)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
    v_owned_count integer;
    v_reference_place_count integer;
    v_reference_route_count integer;
    v_preserved_count integer := 0;
    v_record record;
    v_place_id bigint;
    v_folder_id bigint;
    v_link_id bigint;
begin
    if jsonb_typeof(coalesce(p_preserved_places, '[]'::jsonb)) <> 'array' then
        raise exception 'p_preserved_places must be a JSON array';
    end if;

    perform 1
    from public.tasks as task
    where task.id = p_task_id
    for update;

    if not found then
        raise exception 'Task % does not exist', p_task_id;
    end if;

    select
        count(*) filter (where relationship = 'owner' and place_id is not null),
        count(*) filter (where relationship = 'reference' and place_id is not null),
        count(*) filter (where route_id is not null)
    into v_owned_count, v_reference_place_count, v_reference_route_count
    from public.task_map_links
    where task_id = p_task_id;

    for v_record in
        select item.value as item
        from jsonb_array_elements(coalesce(p_preserved_places, '[]'::jsonb)) as item(value)
    loop
        v_place_id := nullif(v_record.item ->> 'place_id', '')::bigint;
        v_folder_id := nullif(v_record.item ->> 'folder_id', '')::bigint;

        if v_place_id is null or v_folder_id is null then
            raise exception 'Each preserved place requires place_id and folder_id';
        end if;

        select link.id
        into v_link_id
        from public.task_map_links as link
        where link.task_id = p_task_id
          and link.place_id = v_place_id
          and link.relationship = 'owner'
        for update;

        if not found then
            raise exception 'Task % does not own place %', p_task_id, v_place_id;
        end if;

        update public.task_map_links
        set relationship = 'reference',
            client_draft_id = null
        where id = v_link_id;

        update public.map_places
        set folder_id = v_folder_id,
            name = coalesce(nullif(btrim(v_record.item ->> 'name'), ''), name)
        where id = v_place_id;

        v_preserved_count := v_preserved_count + 1;
    end loop;

    delete from public.tasks
    where id = p_task_id;

    return jsonb_build_object(
        'deleted_task_id', p_task_id,
        'deleted_owned_place_count', v_owned_count - v_preserved_count,
        'preserved_place_count', v_preserved_count,
        'removed_reference_place_count', v_reference_place_count,
        'removed_reference_route_count', v_reference_route_count
    );
end;
$$;

create or replace function public.nl_get_maps_snapshot()
returns jsonb
language sql
stable
security invoker
set search_path = ''
as $$
    select jsonb_build_object(
        'folders', coalesce((
            select jsonb_agg(to_jsonb(folder) order by folder.is_default desc, lower(folder.name), folder.id)
            from public.map_folders as folder
        ), '[]'::jsonb),
        'places', coalesce((
            select jsonb_agg(to_jsonb(place) order by lower(place.name), place.id)
            from public.map_places as place
