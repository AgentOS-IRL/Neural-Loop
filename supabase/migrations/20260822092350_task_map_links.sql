create or replace function public.nl_validate_task_map_link()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
declare
    v_place public.map_places;
    v_default_folder_id bigint;
begin
    if new.route_id is not null then
        if new.relationship <> 'reference' then
            raise exception 'Routes can only be linked as references';
        end if;
        return new;
    end if;

    select place.*
    into v_place
    from public.map_places as place
    where place.id = new.place_id
    for update;

    if not found then
        raise exception 'Map place % does not exist', new.place_id;
    end if;

    if v_place.kind <> 'saved' then
        raise exception 'Parked places cannot be linked to tasks';
    end if;

    if new.relationship = 'owner' then
        select folder.id
        into v_default_folder_id
        from public.map_folders as folder
        where folder.is_default = true;

        if v_default_folder_id is null then
            raise exception 'The Unfiled folder is missing';
        end if;

        if v_place.folder_id <> v_default_folder_id then
            raise exception 'Task-owned places must remain in Unfiled';
        end if;

        if exists (
            select 1
            from public.task_map_links as existing
            where existing.place_id = new.place_id
              and existing.id <> new.id
        ) then
            raise exception 'A task-owned place cannot have other task links';
        end if;
    elsif exists (
        select 1
        from public.task_map_links as existing
        where existing.place_id = new.place_id
          and existing.relationship = 'owner'
          and existing.id <> new.id
    ) then
        raise exception 'Save the task-owned place permanently before linking it to another task';
    end if;

    return new;
end;
$$;

