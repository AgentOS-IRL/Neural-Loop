            select jsonb_agg(to_jsonb(route) order by lower(route.name), route.id)
            from public.map_routes as route
        ), '[]'::jsonb),
        'route_waypoints', coalesce((
            select jsonb_agg(to_jsonb(waypoint) order by waypoint.route_id, waypoint.order_index, waypoint.id)
            from public.map_route_waypoints as waypoint
        ), '[]'::jsonb),
        'task_links', coalesce((
            select jsonb_agg(
                jsonb_build_object(
                    'id', link.id,
                    'task_id', link.task_id,
                    'task_title', task.title,
                    'place_id', link.place_id,
                    'route_id', link.route_id,
                    'relationship', link.relationship,
                    'position', link.position,
                    'client_draft_id', link.client_draft_id,
                    'created_at', link.created_at,
                    'updated_at', link.updated_at
                ) order by lower(task.title), task.id, link.position, link.id
            )
            from public.task_map_links as link
            join public.tasks as task on task.id = link.task_id
        ), '[]'::jsonb)
    );
$$;

