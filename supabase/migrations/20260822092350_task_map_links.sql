create or replace function public.nl_get_task_map_attachments(p_task_id bigint)
returns jsonb
language sql
stable
security invoker
set search_path = ''
as $$
    select coalesce(jsonb_agg(
        jsonb_build_object(
            'id', link.id,
            'task_id', link.task_id,
            'task_title', task.title,
            'place_id', link.place_id,
            'route_id', link.route_id,
            'relationship', link.relationship,
            'position', link.position,
            'client_draft_id', link.client_draft_id,
            'created_at', link.created_at,
            'updated_at', link.updated_at,
            'place', case when link.place_id is not null then to_jsonb(place) else null end,
            'route', case when link.route_id is not null then to_jsonb(route) else null end,
            'route_waypoints', case
                when link.route_id is null then '[]'::jsonb
                else coalesce((
                    select jsonb_agg(to_jsonb(waypoint) order by waypoint.order_index, waypoint.id)
                    from public.map_route_waypoints as waypoint
                    where waypoint.route_id = link.route_id
                ), '[]'::jsonb)
            end
        ) order by link.position, link.id
    ), '[]'::jsonb)
    from public.task_map_links as link
    join public.tasks as task on task.id = link.task_id
    left join public.map_places as place on place.id = link.place_id
    left join public.map_routes as route on route.id = link.route_id
    where link.task_id = p_task_id;
$$;

