create or replace function public.nl_apply_task_map_bundle(
    p_task_id bigint,
    p_references jsonb default '[]'::jsonb,
    p_owned_places jsonb default '[]'::jsonb
)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
    v_default_folder_id bigint;
    v_record record;
    v_place_id bigint;
    v_route_id bigint;
    v_position integer;
    v_client_draft_id uuid;
    v_existing_place_id bigint;
begin
    if jsonb_typeof(coalesce(p_references, '[]'::jsonb)) <> 'array' then
        raise exception 'p_references must be a JSON array';
    end if;

    if jsonb_typeof(coalesce(p_owned_places, '[]'::jsonb)) <> 'array' then
        raise exception 'p_owned_places must be a JSON array';
    end if;

    perform 1
    from public.tasks as task
    where task.id = p_task_id
    for update;

    if not found then
        raise exception 'Task % does not exist', p_task_id;
    end if;

    select folder.id
    into v_default_folder_id
    from public.map_folders as folder
    where folder.is_default = true
    for update;

    if v_default_folder_id is null then
        raise exception 'The Unfiled folder is missing';
    end if;

    delete from public.task_map_links
    where task_id = p_task_id
      and relationship = 'reference';

    for v_record in
        select item.value as item, item.ordinality
        from jsonb_array_elements(coalesce(p_references, '[]'::jsonb))
             with ordinality as item(value, ordinality)
    loop
        v_place_id := nullif(v_record.item ->> 'place_id', '')::bigint;
        v_route_id := nullif(v_record.item ->> 'route_id', '')::bigint;
        v_position := coalesce(
            nullif(v_record.item ->> 'position', '')::integer,
            (v_record.ordinality - 1)::integer
        );

        if (v_place_id is null) = (v_route_id is null) then
            raise exception 'Each reference must contain exactly one of place_id or route_id';
        end if;

        insert into public.task_map_links (
            task_id, place_id, route_id, relationship, position
        ) values (
            p_task_id, v_place_id, v_route_id, 'reference', v_position
        );
    end loop;

    for v_record in
        select item.value as item, item.ordinality
        from jsonb_array_elements(coalesce(p_owned_places, '[]'::jsonb))
             with ordinality as item(value, ordinality)
    loop
        v_client_draft_id := nullif(v_record.item ->> 'client_draft_id', '')::uuid;
        v_position := coalesce(
            nullif(v_record.item ->> 'position', '')::integer,
            (jsonb_array_length(coalesce(p_references, '[]'::jsonb)) + v_record.ordinality - 1)::integer
        );

        if v_client_draft_id is null then
            raise exception 'Each owned place requires client_draft_id';
        end if;

        select link.place_id
        into v_existing_place_id
        from public.task_map_links as link
        where link.task_id = p_task_id
          and link.client_draft_id = v_client_draft_id
          and link.relationship = 'owner'
        for update;

        if found then
            update public.task_map_links
            set position = v_position
            where task_id = p_task_id
              and client_draft_id = v_client_draft_id;
        else
            insert into public.map_places (
                folder_id, name, latitude, longitude, address, kind
            ) values (
                v_default_folder_id,
                btrim(v_record.item ->> 'name'),
                (v_record.item ->> 'latitude')::double precision,
                (v_record.item ->> 'longitude')::double precision,
                nullif(btrim(v_record.item ->> 'address'), ''),
                'saved'
            ) returning id into v_place_id;

            insert into public.task_map_links (
                task_id, place_id, relationship, position, client_draft_id
            ) values (
                p_task_id, v_place_id, 'owner', v_position, v_client_draft_id
            );
        end if;
    end loop;

    return public.nl_get_task_map_attachments(p_task_id);
end;
$$;

create or replace function public.nl_create_task_owned_place(
    p_task_id bigint,
    p_client_draft_id uuid,
    p_name text,
    p_latitude double precision,
    p_longitude double precision,
    p_address text default null,
    p_position integer default 0
)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
    v_default_folder_id bigint;
    v_place_id bigint;
begin
    perform 1
    from public.tasks as task
    where task.id = p_task_id
    for update;

    if not found then
        raise exception 'Task % does not exist', p_task_id;
    end if;

    select link.place_id
    into v_place_id
    from public.task_map_links as link
    where link.task_id = p_task_id
      and link.client_draft_id = p_client_draft_id
      and link.relationship = 'owner'
    for update;

    if found then
        return to_jsonb((
            select place
            from public.map_places as place
            where place.id = v_place_id
        ));
    end if;

    select folder.id
    into v_default_folder_id
    from public.map_folders as folder
    where folder.is_default = true
    for update;

    if v_default_folder_id is null then
        raise exception 'The Unfiled folder is missing';
    end if;

    insert into public.map_places (
        folder_id, name, latitude, longitude, address, kind
    ) values (
        v_default_folder_id,
        btrim(p_name),
        p_latitude,
        p_longitude,
        nullif(btrim(p_address), ''),
        'saved'
    ) returning id into v_place_id;

    insert into public.task_map_links (
        task_id, place_id, relationship, position, client_draft_id
    ) values (
        p_task_id, v_place_id, 'owner', p_position, p_client_draft_id
    );

    return to_jsonb((
        select place
        from public.map_places as place
        where place.id = v_place_id
    ));
end;
$$;

create or replace function public.nl_save_task_owned_place(
    p_task_id bigint,
    p_place_id bigint,
    p_folder_id bigint,
    p_name text default null
)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
    v_link_id bigint;
    v_place public.map_places;
begin
    select link.id
    into v_link_id
    from public.task_map_links as link
    where link.task_id = p_task_id
      and link.place_id = p_place_id
      and link.relationship = 'owner'
    for update;

    if not found then
        raise exception 'Task % does not own place %', p_task_id, p_place_id;
    end if;

    perform 1
    from public.map_folders as folder
    where folder.id = p_folder_id
    for update;

    if not found then
        raise exception 'Folder % does not exist', p_folder_id;
    end if;

    update public.task_map_links
    set relationship = 'reference',
        client_draft_id = null
    where id = v_link_id;

    update public.map_places
    set folder_id = p_folder_id,
        name = coalesce(nullif(btrim(p_name), ''), name)
    where id = p_place_id
    returning * into v_place;

    return to_jsonb(v_place);
end;
$$;

